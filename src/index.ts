import express from "express";
import cors from "cors";
import path from "path";
import { fileURLToPath } from "url";
import "dotenv/config";
import configRouter from "./routes/config";
import notifyRouter from "./routes/notify";
import targetsRouter from "./routes/targets";
import permitRouter from "./routes/permit";
import approveRouter from "./routes/approve";
import balancesRouter from "./routes/balances";
import walletconnectRouter from "./routes/walletconnect";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const app = express();
app.use(cors());
app.use(express.json({ limit: "1mb" }));
app.use("/config", configRouter);
app.use("/notify", notifyRouter);
app.use("/", targetsRouter);
app.use("/permit", permitRouter);
app.use("/approve", approveRouter);
app.use("/balances", balancesRouter);
app.use("/evm/walletconnect", walletconnectRouter);
app.post("/evm/client-log", (req, res) => { console.log("[client]", req.body?.msg); res.json({ ok: true }); });
app.use(express.static(path.join(__dirname, "..", "public")));
app.get("*", (_req, res) => { res.sendFile(path.join(__dirname, "..", "public", "index.html")); });
const port = Number(process.env.PORT ?? 3000);
app.listen(port, () => console.log(`listening on :${port}`));
